-- ~/.config/nvim/lua/core/options.lua
local opt = vim.opt

-- =============================================================================
--  Интерфейс (UI)
-- =============================================================================
opt.number = true         -- абсолютные номера строк
opt.relativenumber = true -- относительные номера (удобно для 5j, 10k)
opt.signcolumn = "yes"    -- колонка для значков (гит, линтер)
opt.wrap = false          -- не переносить длинные строки
opt.scrolloff = 8         -- отступ от края при скролле
opt.termguicolors = true  -- 24-bit цвета (нужно для onedark)
opt.laststatus = 3        -- глобальный статуслайн (один на все окна)
opt.cmdheight = 1         -- высота командной строки
-- opt.winbar = "%f %m %r"   -- резерв места под winbar (для хлебных крошек)
-- opt.statusline = "%=%l,%c" -- только координаты внизу
opt.showtabline = 2 -- всегда показывать табы

opt.tabpagemax = 1
-- В options.lua
-- opt.statuscolumn = "%s %l %C %@v:lua.Scrollbar@"

-- =============================================================================
--  Отступы и форматирование
-- =============================================================================
opt.tabstop = 4        -- ширина таба = 4 пробела
opt.shiftwidth = 4     -- отступ при >> и <<
opt.expandtab = true   -- табы заменять на пробелы
opt.smartindent = true -- умные отступы при вставке

-- =============================================================================
--  Сплиты и окна
-- =============================================================================
opt.splitbelow = true -- новые сплиты открываются снизу
opt.splitright = true -- новые вертикальные сплиты справа
opt.hidden = true     -- переключение буферов без сохранения

-- =============================================================================
--  Поиск
-- =============================================================================
opt.ignorecase = true -- игнорировать регистр при поиске
opt.smartcase = true  -- учитывать регистр если есть заглавные буквы

-- =============================================================================
--  Производительность и LSP
-- =============================================================================
opt.updatetime = 100 -- быстрее обновление (LSP, gitsigns)

-- =============================================================================
--  Буфер обмена
-- =============================================================================
opt.clipboard = "unnamedplus" -- системный буфер обмена

-- =============================================================================
--  Автодополнение
-- =============================================================================
--  opt.completeopt = "menuone,noinsert,noselect" -- меню без авто-вставки
opt.wildmode = "longest:full,full" -- умное автодополнение в cmdline

